"""Render a mission: report.html (rich view), README.md (GitHub view with mermaid), missions/INDEX.md.

Usage: mission_render.py <slug|path> [--open] [--no-mark]

report.html is overwritten in place: one report per mission, never a new dated file.
The "Latest changes" view covers changes since the previous report. After rendering,
last_report_at is set to now (skip with --no-mark).
"""
from __future__ import annotations

import json
import sys

from mission_lib import MISSIONS_DIR, SKILL_DIR, gh_url, load, load_computed, mission_dir, now_utc, run, save


def _mm(s: str) -> str:
    return str(s).replace('"', "'").replace("\n", " ")[:60]


def readme(m: dict, c: dict, ts: str) -> str:
    ri = m.get("root_issue") or {}
    L = [f"<!-- generated by the mission skill at {ts}. Do not edit: edit mission.yaml, then /mission update. -->",
         f"# Mission: {m['title']}", "",
         f"**Status:** {m['status']} · **Root issue:** {ri.get('url') or 'none'} · **Record:** [mission.yaml](mission.yaml) · **Updated:** {m.get('updated')}", "",
         "## Destination", str(m.get("destination", "")).strip(), ""]
    nm = m.get("next_milestone")
    if nm:
        L += ["## Next milestone", f"**{nm.get('title')}**. Done when: {nm.get('done_when', '')} Owner: {nm.get('owner', '')}.", ""]
    needs = [n for n in m.get("needs_you") or [] if n.get("blocking", True)]
    L += ["## Needs Gabriel", *(f"- **{n['id']}** ({n.get('since', '')}): {n['question']}" for n in needs)] if needs else ["## Needs Gabriel", "Nothing."]
    L.append("")
    live = [d for d in m.get("decisions") or [] if d.get("state") == "ratified"]
    if live:
        L += ["## Decisions in force", *(f"- **{d['id']}**: {d['statement']}" for d in live), ""]
    prop = [d for d in m.get("decisions") or [] if d.get("state") == "proposed"]
    if prop:
        L += ["## Proposed, not ratified", *(f"- **{d['id']}**: {d['statement']}" for d in prop), ""]
    if m.get("disproven"):
        L += ["## Do not reload (disproven)", *(f"- **{x['id']}** False: {x['claim']}" for x in m["disproven"]), ""]
    if m.get("scope_constraints"):
        L += ["## Scope constraints", *(f"- {s}" for s in m["scope_constraints"]), ""]
    js = m.get("journey") or []
    if js:
        L += ["## Journey", "```mermaid", "flowchart LR"]
        for i, j in enumerate(js):
            label = f"{j['id']} {str(j.get('start', ''))[:10]}<br/>{_mm(j.get('summary', ''))}"
            L.append(f'  {j["id"].replace("-", "")}["{label}"]')
            if i:
                L.append(f'  {js[i - 1]["id"].replace("-", "")} --> {j["id"].replace("-", "")}')
            if j.get("kind") in ("gap", "commit_only"):
                L.append(f'  style {j["id"].replace("-", "")} stroke:#d03b3b,stroke-dasharray:4')
        L += ["```", ""]
    g = m.get("graph") or {}
    if g.get("nodes"):
        L += ["## Context graph", "```mermaid", "graph TD"]
        L += [f'  {n["id"].replace("-", "_")}["{_mm(n.get("label", n["id"]))}"]' for n in g["nodes"]]
        L += [f'  {e["from"].replace("-", "_")} -->|{_mm(e.get("label", ""))}| {e["to"].replace("-", "_")}' if e.get("label")
              else f'  {e["from"].replace("-", "_")} --> {e["to"].replace("-", "_")}' for e in g.get("edges", [])]
        L += ["```", ""]
    if m.get("members"):
        L += ["## Members", *(f"- [{x['ref']}]({x['url']}): {x['title']} ({x['role']})" if x.get("url") else f"- {x['ref']}: {x['title']} ({x['role']})" for x in m["members"]), ""]
    if c.get("fetched_at"):
        L += [f"Trackers fetched {c['fetched_at']}: {c.get('mismatches', 0)} mismatch(es). Open `report.html` for the full view.", ""]
    return "\n".join(L)


def index() -> str:
    rows = []
    for f in sorted(MISSIONS_DIR.glob("*/mission.yaml")):
        m = load(f.parent)
        ri = m.get("root_issue") or {}
        rows.append(f"| [{m['slug']}]({m['slug']}/README.md) | {m['title']} | {m['status']} | {ri.get('url') or ''} | {m.get('updated', '')} |")
    return "\n".join(["# Missions", "",
                      "One folder per mission. `mission.yaml` is the main record. Generated by the mission skill. Do not edit.", "",
                      "| Mission | Title | Status | Root issue | Updated |", "|---|---|---|---|---|", *rows, ""])


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    d = mission_dir(sys.argv[1])
    m, c, ts = load(d), load_computed(d), now_utc()
    data = {"mission": json.loads(json.dumps(m, default=str)), "computed": c, "generated_at": ts,
            "record_url": gh_url(d / "mission.yaml")}
    tpl = (SKILL_DIR / "assets" / "template.html").read_text()
    payload = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    (d / "report.html").write_text(tpl.replace("/*__DATA__*/null", payload))
    (d / "README.md").write_text(readme(m, c, ts))
    (MISSIONS_DIR / "INDEX.md").write_text(index())
    if "--no-mark" not in sys.argv:
        m["last_report_at"] = ts
        save(d, m)
    print(f"file://{d / 'report.html'}")
    if "--open" in sys.argv:
        run(["open", str(d / "report.html")], check=False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
