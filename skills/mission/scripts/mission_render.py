"""Render a mission: report.html (rich view, with the Closure tab), README.md (GitHub view with mermaid), missions/INDEX.md.

Usage: mission_render.py <slug|path> [--open] [--no-mark]

report.html is overwritten in place: one report per mission, never a new dated file.
The "Latest changes" view covers changes since the previous report. A render more than
2 hours after the last one moves the window (report_window_start = old last_report_at,
last_report_at = now). Renders closer together keep the same window. --no-mark never moves it.
Only those two lines of mission.yaml are touched, so the file is never reflowed.
"""
from __future__ import annotations

import json
import sys

import datetime as dt

from mission_closure import render_closure
from mission_lib import JIRA_BROWSE, JIRA_KEY_PATTERN, MISSIONS_DIR, SKILL_DIR, gh_url, load, load_computed, mission_dir, now_utc, run, set_top
from mission_links import e, linkify

WINDOW_HOLD_HOURS = 2


def _mm(s: str) -> str:
    return str(s).replace('"', "'").replace("\n", " ")[:60]


def _age_hours(v) -> float:
    t = v if isinstance(v, dt.datetime) else dt.datetime.fromisoformat(str(v).replace("Z", "+00:00"))
    t = t if t.tzinfo else t.replace(tzinfo=dt.timezone.utc)
    return (dt.datetime.now(dt.timezone.utc) - t).total_seconds() / 3600


def _iso(v) -> str | None:
    if v in (None, ""):
        return None
    t = v if isinstance(v, dt.datetime) else dt.datetime.fromisoformat(str(v).replace("Z", "+00:00"))
    t = t if t.tzinfo else t.replace(tzinfo=dt.timezone.utc)
    return t.astimezone(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def readme(m: dict, c: dict, ts: str) -> str:
    ri = m.get("root_issue") or {}
    L = [f"<!-- generated by the mission skill at {ts}. Do not edit: edit mission.yaml, then /mission update. -->",
         f"# Mission: {m['title']}", "",
         f"**Status:** {m['status']} · **Root issue:** {ri.get('url') or 'none'} · **Record:** [mission.yaml](mission.yaml) · **Updated:** {m.get('updated')}", "",
         "## Destination", str(m.get("destination", "")).strip(), ""]
    nm = m.get("next_milestone")
    if nm:
        L += ["## Next milestone", f"**{nm.get('title')}**. Done when: {nm.get('done_when', '')} Owner: {nm.get('owner', '')}.", ""]
    needs = [n for n in m.get("needs_you") or [] if n.get("blocking", True)]
    L += ["## Needs Gabriel", *(f"- **{n['id']}** ({n.get('since', '')}): {n['question']}" for n in needs)] if needs else ["## Needs Gabriel", "Nothing."]
    L.append("")
    live = [d for d in m.get("decisions") or [] if d.get("state") == "ratified"]
    if live:
        L += ["## Decisions in force", *(f"- **{d['id']}**: {d['statement']}" for d in live), ""]
    prop = [d for d in m.get("decisions") or [] if d.get("state") == "proposed"]
    if prop:
        L += ["## Proposed, not ratified", *(f"- **{d['id']}**: {d['statement']}" for d in prop), ""]
    if m.get("disproven"):
        L += ["## Do not reload (disproven)", *(f"- **{x['id']}** False: {x['claim']}" for x in m["disproven"]), ""]
    if m.get("scope_constraints"):
        L += ["## Scope constraints", *(f"- {s}" for s in m["scope_constraints"]), ""]
    js = m.get("journey") or []
    if js:
        L += ["## Journey", "```mermaid", "flowchart LR"]
        for i, j in enumerate(js):
            label = f"{j['id']} {str(j.get('start', ''))[:10]}<br/>{_mm(j.get('summary', ''))}"
            L.append(f'  {j["id"].replace("-", "")}["{label}"]')
            if i:
                L.append(f'  {js[i - 1]["id"].replace("-", "")} --> {j["id"].replace("-", "")}')
            if j.get("kind") in ("gap", "commit_only"):
                L.append(f'  style {j["id"].replace("-", "")} stroke:#d03b3b,stroke-dasharray:4')
        L += ["```", ""]
    g = m.get("graph") or {}
    if g.get("nodes"):
        L += ["## Context graph", "```mermaid", "graph TD"]
        L += [f'  {n["id"].replace("-", "_")}["{_mm(n.get("label", n["id"]))}"]' for n in g["nodes"]]
        L += [f'  {e["from"].replace("-", "_")} -->|{_mm(e.get("label", ""))}| {e["to"].replace("-", "_")}' if e.get("label")
              else f'  {e["from"].replace("-", "_")} --> {e["to"].replace("-", "_")}' for e in g.get("edges", [])]
        L += ["```", ""]
    if m.get("members"):
        L += ["## Members", *(f"- [{x['ref']}]({x['url']}): {x['title']} ({x['role']})" if x.get("url") else f"- {x['ref']}: {x['title']} ({x['role']})" for x in m["members"]), ""]
    if c.get("fetched_at"):
        L += [f"Trackers fetched {c['fetched_at']}: {c.get('mismatches', 0)} mismatch(es). Open `report.html` for the full view.", ""]
    return "\n".join(L)


def index() -> str:
    rows = []
    for f in sorted(MISSIONS_DIR.glob("*/mission.yaml")):
        m = load(f.parent)
        ri = m.get("root_issue") or {}
        rows.append(f"| [{m['slug']}]({m['slug']}/README.md) | {m['title']} | {m['status']} | {ri.get('url') or ''} | {m.get('updated', '')} |")
    return "\n".join(["# Missions", "",
                      "One folder per mission. `mission.yaml` is the main record. Generated by the mission skill. Do not edit.", "",
                      "| Mission | Title | Status | Root issue | Updated |", "|---|---|---|---|---|", *rows, ""])


def string_leaves(x, out: set) -> set:
    if isinstance(x, str):
        out.add(x)
    elif isinstance(x, dict):
        for v in x.values():
            string_leaves(v, out)
    elif isinstance(x, list):
        for v in x:
            string_leaves(v, out)
    return out


def link_map(m: dict) -> dict:
    """text -> linkified HTML, for every text in the record that holds a reference. The JS views look it up (lk)."""
    out = {}
    for s in string_leaves({k: v for k, v in m.items() if k != "threads"}, set()):
        h = linkify(s)
        if h != e(s):
            out[s] = h
    return out


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    d = mission_dir(sys.argv[1])
    path = render(d, mark="--no-mark" not in sys.argv)
    print(f"file://{path}")
    if "--open" in sys.argv:
        run(["open", str(path)], check=False)
    return 0


def render(d, mark: bool = True):
    """Write report.html (with the Closure tab), README.md and missions/INDEX.md. Return the report path."""
    m, c, ts = load(d), load_computed(d), now_utc()
    last, start = m.get("last_report_at"), m.get("report_window_start")
    shift = last is None or _age_hours(last) > WINDOW_HOLD_HOURS
    window_start = last if shift else start
    closure_html, closure = render_closure(m, d)
    data = {"mission": json.loads(json.dumps(m, default=str)), "computed": c, "generated_at": ts,
            "record_url": gh_url(d / "mission.yaml"), "window_start": _iso(window_start),
            "jira": {"browse": JIRA_BROWSE, "key_pattern": JIRA_KEY_PATTERN}, "closure": closure,
            "lk": link_map(json.loads(json.dumps(m, default=str)))}
    tpl = (SKILL_DIR / "assets" / "template.html").read_text()
    payload = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    page = tpl.replace("<!--__CLOSURE__-->", closure_html).replace("/*__DATA__*/null", payload)
    (d / "report.html").write_text(page)
    (d / "README.md").write_text(readme(m, c, ts))
    (MISSIONS_DIR / "INDEX.md").write_text(index())
    if mark and shift:
        set_top(d, "report_window_start", _iso(last))
        set_top(d, "last_report_at", ts)
    return d / "report.html"


if __name__ == "__main__":
    sys.exit(main())
